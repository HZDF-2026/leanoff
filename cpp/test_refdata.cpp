void testPyFloat() {
    const double vals[] = {0.0, 1.0, 0.984, 0.719, 1.5, 1e16, 1e15,
                           123456789.123, 0.0001, 0.00001, -2.5, 100.0, 3.14159,
                           1234567890123456.0, 0.1, 2.675, 3600.0, 0.03, 0.016};
    const char* want[] = {"0.0", "1.0", "0.984", "0.719", "1.5", "1e+16",
                         "1000000000000000.0", "123456789.123", "0.0001", "1e-05",
                         "-2.5", "100.0", "3.14159", "1234567890123456.0", "0.1",
                         "2.675", "3600.0", "0.03", "0.016"};
    for (size_t i = 0; i < sizeof(vals) / sizeof(vals[0]); i++) {
        checkEq(pyFloat(vals[i]), want[i], std::string("pyFloat #") + std::to_string(i));
    }
    checkEq(pyFloat(std::nan("")), "NaN", "pyFloat NaN");
    checkEq(pyFloat(HUGE_VAL), "Infinity", "pyFloat +inf");
    checkEq(pyFloat(-HUGE_VAL), "-Infinity", "pyFloat -inf");
}

void testRound1() {
    const double vals[] = {0.0, 1.0, 0.984, 0.719, 1.5, 1e16, 123456789.123,
                           0.0001, -2.5, 100.0, 3.14159, 0.1, 2.675, 3600.0,
                           0.03, 0.016};
    const double want[] = {0.0, 1.0, 1.0, 0.7, 1.5, 1e16, 123456789.1, 0.0,
                           -2.5, 100.0, 3.1, 0.1, 2.7, 3600.0, 0.0, 0.0};
    for (size_t i = 0; i < sizeof(vals) / sizeof(vals[0]); i++) {
        double got = round1(vals[i]);
        check(std::memcmp(&got, &want[i], 8) == 0,
              "round1 #" + std::to_string(i) + " (" + pyFloat(vals[i]) + ")");
    }
}

void testPyStr() {
    // (input, expected json.dumps output)
    struct Case {
        const char* in;
        const char* want;
    };
    const Case cases[] = {
        {"simple", "\"simple\""},
        {"with \"quote\"", "\"with \\\"quote\\\"\""},
        {"back\\slash", "\"back\\\\slash\""},
        {"tab\there", "\"tab\\there\""},
        {"nl\nhere", "\"nl\\nhere\""},
        {"ctrl\x01", "\"ctrl\\u0001\""},
        {"euro €", "\"euro \\u20ac\""},
        {"emoji 😀", "\"emoji \\ud83d\\ude00\""},
        {"math ß und ä", "\"math \\u00df und \\u00e4\""},
        {"cjk 中文", "\"cjk \\u4e2d\\u6587\""},
        {"del\x7f", "\"del\\u007f\""},
        {"", "\"\""},
    };
    for (const auto& c : cases) {
        checkEq(pyStr(c.in), c.want, std::string("pyStr ") + c.in);
    }
}

void testPyIntParse() {
    struct Case {
        const char* in;
        bool ok;
        long long v;
    };
    const Case cases[] = {
        {"1_0", true, 10}, {" 4 ", true, 4}, {"+4", true, 4}, {"-4", true, -4},
        {"x", false, 0}, {"1__0", false, 0}, {"_1", false, 0}, {"1_", false, 0},
        {"", false, 0}, {"0", true, 0}, {"  -12  ", true, -12},
    };
    for (const auto& c : cases) {
        long long v = 0;
        bool ok = pyIntParse(c.in, v);
        check(ok == c.ok && (!c.ok || v == c.v),
              std::string("pyIntParse '") + c.in + "'");
    }
    // Python's int is unbounded; long long overflows -> invalid (documented
    // divergence, only reachable via --jobs).
    long long v = 0;
    check(!pyIntParse("9999999999999999999999", v), "pyIntParse overflow");
}

void testSplitLinesTruncate() {
    // C++ hex escapes are greedy ("\x0be" would be 0xBE), so the VT/FF/FS/RS
    // bytes are split off with string concatenation. Python: 8 lines, no
    // trailing empty after the final separator.
    std::vector<std::string> lines = pySplitLines("a\r\nb\nc\rd\x0b" "e\x0c" "f\x1c" "g\x1d" "h\x1e");
    check(lines.size() == 8, "pySplitLines count");
    checkEq(lines[0], "a", "pySplitLines crlf");
    checkEq(lines[1], "b", "pySplitLines lf");
    checkEq(lines[2], "c", "pySplitLines cr");
    checkEq(lines[3], "d", "pySplitLines vt");
    checkEq(lines[7], "h", "pySplitLines rs");
    check(pySplitLines("a\n").size() == 1, "pySplitLines trailing sep");
    check(pySplitLines("").empty(), "pySplitLines empty");
    check(pySplitLines(u8"a\u2028b\u2029c").size() == 3, "pySplitLines unicode seps");

    checkEq(truncateRunes("abcdefghij", 160), "abcdefghij", "truncate under");
    checkEq(truncateRunes("abcdefghij", 4), "abcd", "truncate ascii");
    checkEq(truncateRunes(u8"日本語文", 2), u8"日本", "truncate runes");
    checkEq(truncateRunes("abc", 3), "abc", "truncate exact");
    checkEq(pyStrip("  x  "), "x", "pyStrip spaces");
    checkEq(pyStrip("\t\n\r x \v"), "x", "pyStrip mixed");
    checkEq(pyStrip(""), "", "pyStrip empty");
}

