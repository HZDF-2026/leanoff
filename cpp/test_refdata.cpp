void testParseLeanOutput() {
    const char* out =
        "A.lean:1:0: error: something\n"
        "A.lean:2:0: warning: deprecated\n"
        "A.lean:3:0: info: declaration uses 'sorry'\n"
        "A.lean:4:0: error: another error\n";
    LeanCounts c = parseLeanOutput(out);
    check(c.errors == 2, "parseLeanOutput errors");
    check(c.warnings == 1, "parseLeanOutput warnings");
    check(c.sorries == 1, "parseLeanOutput sorries");
    checkEq(c.first, "A.lean:1:0: error: something", "parseLeanOutput first");
    check(parseLeanOutput("").errors == 0, "parseLeanOutput empty");
    check(parseLeanOutput("plain text\n").first.empty(), "parseLeanOutput no errors");
}

