int failures = 0;
int checks = 0;

void check(bool ok, const std::string& what) {
    checks++;
    if (!ok) {
        failures++;
        std::fprintf(stderr, "FAIL %s\n", what.c_str());
    }
}

void checkEq(const std::string& got, const std::string& want, const std::string& what) {
    checks++;
    if (got != want) {
        failures++;
        std::fprintf(stderr, "FAIL %s\n", what.c_str());
        size_t i = 0;
        while (i < got.size() && i < want.size() && got[i] == want[i]) i++;
        std::fprintf(stderr, "  first diff at byte %zu (got %zu bytes, want %zu bytes)\n",
                     i, got.size(), want.size());
        size_t lo = i >= 20 ? i - 20 : 0;
        std::fprintf(stderr, "  got  [%zu..]: ", lo);
        for (size_t k = lo; k < got.size() && k < lo + 40; k++)
            std::fprintf(stderr, "%02x ", static_cast<unsigned char>(got[k]));
        std::fprintf(stderr, "\n  want [%zu..]: ", lo);
        for (size_t k = lo; k < want.size() && k < lo + 40; k++)
            std::fprintf(stderr, "%02x ", static_cast<unsigned char>(want[k]));
        std::fprintf(stderr, "\n");
        std::fprintf(stderr, "  got:  %s\n  want: %s\n", got.c_str(), want.c_str());
    }
}

