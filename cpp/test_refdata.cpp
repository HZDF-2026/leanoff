void testTopoLevels() {
    auto mk = [](const char* n, std::vector<std::string> deps) {
        return Module{n, std::string("fake/") + n + ".lean", std::move(deps)};
    };
    // chain: C imports B imports A
    std::vector<Module> chain = {mk("A", {}), mk("B", {"A"}), mk("C", {"B"})};
    auto levels = topoLevels(chain);
    check(levels.size() == 3, "chain levels");
    checkEq(levels[0][0].name, "A", "chain level0");
    checkEq(levels[1][0].name, "B", "chain level1");
    checkEq(levels[2][0].name, "C", "chain level2");

    // diamond: D imports B and C; both import A
    std::vector<Module> dia = {mk("D", {"B", "C"}), mk("B", {"A"}), mk("C", {"A"}), mk("A", {})};
    levels = topoLevels(dia);
    check(levels.size() == 3, "diamond levels");
    checkEq(levels[0][0].name, "A", "diamond level0");
    check(levels[1].size() == 2, "diamond level1 size");
    checkEq(levels[1][0].name, "B", "diamond level1 first");
    checkEq(levels[1][1].name, "C", "diamond level1 second");
    checkEq(levels[2][0].name, "D", "diamond level2");

    // cycle: A <-> B
    std::vector<Module> cyc = {mk("A", {"B"}), mk("B", {"A"})};
    bool threw = false;
    try {
        topoLevels(cyc);
    } catch (const std::runtime_error& e) {
        threw = true;
        checkEq(e.what(), "leanoff: import cycle among: A, B", "cycle message");
    }
    check(threw, "cycle throws");
}

