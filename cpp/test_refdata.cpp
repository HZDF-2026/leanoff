void runCli(const std::vector<std::string>& args, std::ostringstream& out,
            std::ostringstream& err, int& rc) {
    out.str("");
    err.str("");
    rc = cliMain(args, out, err);
}

void testCli() {
    std::ostringstream out, err;
    int rc = 0;

    // help surfaces
    runCli({"-h"}, out, err, rc);
    check(rc == 0, "cli -h exit");
    check(out.str().rfind("usage: leanoff [-h] {verify,build} ...\n", 0) == 0, "cli -h usage");
    check(out.str().find("positional arguments:") != std::string::npos, "cli -h body");
    check(out.str().find("show this help message and exit\n") != std::string::npos, "cli -h tail");
    check(err.str().empty(), "cli -h stderr");

    runCli({"verify", "-h"}, out, err, rc);
    check(rc == 0, "cli verify -h exit");
    check(out.str().rfind("usage: leanoff verify [-h] [--root ROOT]", 0) == 0,
          "cli verify -h usage");
    check(out.str().find("--allow-sorry         do not fail on sorry\n") != std::string::npos,
          "cli verify -h body");

    runCli({"build", "-h"}, out, err, rc);
    check(rc == 0, "cli build -h exit");
    check(out.str().find("[--out OUT]") != std::string::npos, "cli build -h out");
    check(out.str().find("olean output directory (default:\n"
                        "                        <root>/.leanoff/olean)") != std::string::npos,
          "cli build -h out wrap");

    // missing / invalid subcommand
    runCli({}, out, err, rc);
    check(rc == 2, "cli no-args exit");
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: the following arguments are required: cmd\n",
            "cli no-args");

    runCli({"frobnicate"}, out, err, rc);
    check(rc == 2, "cli bad choice exit");
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: argument cmd: invalid choice: 'frobnicate' "
            "(choose from 'verify', 'build')\n",
            "cli bad choice");

    // unrecognized: reported by the top parser after a clean sub parse
    runCli({"verify", "--frob"}, out, err, rc);
    check(rc == 2, "cli sub unrecognized exit");
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: unrecognized arguments: --frob\n",
            "cli sub unrecognized");

    runCli({"verify", "extra", "more"}, out, err, rc);
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: unrecognized arguments: extra more\n",
            "cli sub positionals");

    // sub-level usage errors use the sub usage and prefix
    runCli({"verify", "--format", "xml"}, out, err, rc);
    check(rc == 2, "cli invalid choice exit");
    checkEq(err.str(),
            "usage: leanoff verify [-h] [--root ROOT] [--lean LEAN] [--lean-path LEAN_PATH]\n"
            "                      [--filter FILTER] [--jobs JOBS] [--allow-sorry]\n"
            "                      [--format {text,json}]\n"
            "leanoff verify: error: argument --format: invalid choice: 'xml' "
            "(choose from 'text', 'json')\n",
            "cli invalid choice");

    runCli({"verify", "--jobs", "x"}, out, err, rc);
    checkEq(err.str(),
            "usage: leanoff verify [-h] [--root ROOT] [--lean LEAN] [--lean-path LEAN_PATH]\n"
            "                      [--filter FILTER] [--jobs JOBS] [--allow-sorry]\n"
            "                      [--format {text,json}]\n"
            "leanoff verify: error: argument --jobs: invalid int value: 'x'\n",
            "cli invalid int");

    runCli({"verify", "--l", "."}, out, err, rc);
    checkEq(err.str(),
            "usage: leanoff verify [-h] [--root ROOT] [--lean LEAN] [--lean-path LEAN_PATH]\n"
            "                      [--filter FILTER] [--jobs JOBS] [--allow-sorry]\n"
            "                      [--format {text,json}]\n"
            "leanoff verify: error: ambiguous option: --l could match --lean, --lean-path\n",
            "cli ambiguous");

    runCli({"verify", "--root"}, out, err, rc);
    checkEq(err.str().substr(err.str().find("leanoff verify: error:")),
            "leanoff verify: error: argument --root: expected one argument\n",
            "cli expected one argument");

    runCli({"verify", "--allow-sorry=x"}, out, err, rc);
    checkEq(err.str().substr(err.str().find("leanoff verify: error:")),
            "leanoff verify: error: argument --allow-sorry: ignored explicit argument 'x'\n",
            "cli ignored explicit");

    // "--" semantics
    runCli({"--", "verify"}, out, err, rc);
    check(rc == 2, "cli -- verify exit");
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: argument cmd: invalid choice: '--' "
            "(choose from 'verify', 'build')\n",
            "cli -- verify");

    runCli({"verify", "--", "x"}, out, err, rc);
    checkEq(err.str(),
            "usage: leanoff [-h] {verify,build} ...\n"
            "leanoff: error: unrecognized arguments: -- x\n",
            "cli verify -- x");

    // left-to-right: help after a bad option still errors; before it wins
    runCli({"verify", "--format", "xml", "-h"}, out, err, rc);
    check(rc == 2, "cli error-then-help exit");
    runCli({"verify", "-h", "--format", "xml"}, out, err, rc);
    check(rc == 0, "cli help-then-error exit");

    // negative numbers and lone "-" are values, not options
    runCli({"verify", "--jobs", "-x"}, out, err, rc);
    checkEq(err.str().substr(err.str().find("leanoff verify: error:")),
            "leanoff verify: error: argument --jobs: expected one argument\n",
            "cli dash value refused");
}

