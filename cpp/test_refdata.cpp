// Scheduling with an injected runLean: a fake toolchain over a temp tree.
// RunLeanFunc is a plain function pointer, so the fake records into
// file-scope statics.
std::vector<std::string> g_ran;  // module names in run order
std::string g_failName;         // module to fail; empty = all pass
std::string g_sorryName;        // module to report one sorry for

Result fakeRunLean(const std::string& exe, const std::string& root, const Module& mod,
                   const std::string& leanPath, const std::string& outOlean,
                   bool cwdRoot) {
    (void)exe; (void)root; (void)leanPath; (void)outOlean; (void)cwdRoot;
    g_ran.push_back(mod.name);
    bool bad = !g_failName.empty() && mod.name == g_failName;
    int sorries = (!g_sorryName.empty() && mod.name == g_sorryName) ? 1 : 0;
    return Result{mod.name, !bad, bad ? 1 : 0, 0, sorries, 0.001,
                  bad ? mod.name + ".lean:1:0: error: fake failure" : ""};
}

namespace fs = std::filesystem;

void putFile(const fs::path& p, const std::string& text) {
    std::FILE* f = std::fopen(p.u8string().c_str(), "wb");
    if (!f) return;
    std::fwrite(text.data(), 1, text.size(), f);
    std::fclose(f);
}

std::string joinNames(std::vector<std::string> names) {
    std::sort(names.begin(), names.end());
    std::string out;
    for (size_t i = 0; i < names.size(); i++) {
        if (i > 0) out += ",";
        out += names[i];
    }
    return out;
}

int countOccurrences(const std::string& s, const std::string& needle) {
    int n = 0;
    for (size_t pos = s.find(needle); pos != std::string::npos;
         pos = s.find(needle, pos + needle.size())) {
        n++;
    }
    return n;
}

// RAII temp directory under the system temp; ASCII-only names.
struct TempDir {
    fs::path path;
    bool ok = false;

    TempDir() {
        std::error_code ec;
        fs::path base = fs::temp_directory_path(ec);
        if (ec) return;
        for (int i = 0; i < 100; i++) {
            fs::path d = base / ("leanoff_test_" + std::to_string(i));
            if (fs::create_directory(d, ec)) {
                path = d;
                ok = true;
                return;
            }
        }
    }
    ~TempDir() {
        if (ok) {
            std::error_code ec;
            fs::remove_all(path, ec);
        }
    }
};

void testScheduling() {
    TempDir tmp;
    check(tmp.ok, "temp dir");
    if (!tmp.ok) return;

    // A imports sub.B; sub.B has no imports; sub.C imports sub.B.
    std::error_code ec;
    fs::path root = tmp.path / "proj";
    fs::create_directories(root / "sub", ec);
    putFile(root / "A.lean", "import sub.B\n");
    putFile(root / "sub" / "B.lean", "-- no imports\n");
    putFile(root / "sub" / "C.lean", "import sub.B\n");
    // Dummy executable: findToolchain only checks existence — the engine never
    // spawns lean because runLeanFn is injected.
    fs::path tc = tmp.path / "toolchain";
    fs::create_directories(tc, ec);
#ifdef _WIN32
    putFile(tc / "lean.exe", "");
#else
    putFile(tc / "lean", "");
#endif

    Options o;
    o.root = root.u8string();
    o.lean = tc.u8string();
    o.jobs = 2;
    o.format = "text";

    Engine eng;
    eng.runLeanFn = &fakeRunLean;
    std::ostringstream t;
    eng.out = &t;

    // verify: every module runs, all pass
    g_ran.clear(); g_failName.clear(); g_sorryName.clear();
    t.str("");
    int rc = eng.verify(o);
    check(rc == 0, "verify pass exit");
    checkEq(joinNames(g_ran), "A,sub.B,sub.C", "verify pass ran");
    check(countOccurrences(t.str(), "PASS") == 3, "verify pass PASSes");

    // verify: a failure does not cancel the remaining modules
    g_ran.clear(); g_failName = "sub.B";
    t.str("");
    rc = eng.verify(o);
    check(rc == 1, "verify fail exit");
    checkEq(joinNames(g_ran), "A,sub.B,sub.C", "verify fail ran all");
    check(countOccurrences(t.str(), "PASS") == 2, "verify fail PASSes");
    check(countOccurrences(t.str(), "FAIL") == 1, "verify fail FAILs");
    check(t.str().find("3 modules: 1 failed, 1 errors, 0 warnings, 0 sorry") !=
              std::string::npos,
          "verify fail summary");
    check(t.str().find("fake failure") != std::string::npos, "verify fail first error");

    // verify: a sorry fails unless --allow-sorry
    g_ran.clear(); g_failName.clear(); g_sorryName = "sub.C";
    t.str("");
    rc = eng.verify(o);
    check(rc == 1, "verify sorry exit");
    Options os = o;
    os.allowSorry = true;
    t.str("");
    rc = eng.verify(os);
    check(rc == 0, "verify allow-sorry exit");

    // verify: --filter narrows the module set
    g_ran.clear(); g_sorryName.clear();
    Options of = o;
    of.filter = "^A$";
    t.str("");
    rc = eng.verify(of);
    check(rc == 0, "verify filter exit");
    checkEq(joinNames(g_ran), "A", "verify filter ran");

    // build: level 0 = [sub.B], level 1 = [A, sub.C]; the olean tree appears
    // under <root>/.leanoff/olean
    g_ran.clear(); g_failName.clear();
    t.str("");
    rc = eng.build(o);
    check(rc == 0, "build pass exit");
    checkEq(joinNames(g_ran), "A,sub.B,sub.C", "build pass ran");
    check(fs::is_directory(root / ".leanoff" / "olean", ec), "build olean dir");

    // build: a failed level stops the build ??queued level-1 modules never run
    g_ran.clear(); g_failName = "sub.B";
    t.str("");
    rc = eng.build(o);
    check(rc == 1, "build fail exit");
    checkEq(joinNames(g_ran), "sub.B", "build fail stopped at level 0");
    check(t.str().find("1 modules: 1 failed") != std::string::npos,
          "build fail summary");

    // build: --out relocates the olean tree
    g_ran.clear(); g_failName.clear();
    Options oo = o;
    oo.out = (tmp.path / "elsewhere").u8string();
    t.str("");
    rc = eng.build(oo);
    check(rc == 0, "build out exit");
    check(fs::is_directory(tmp.path / "elsewhere", ec), "build out dir");

    // an import cycle is a build setup error; verify is unaffected
    fs::create_directories(tmp.path / "cyc", ec);
    putFile(tmp.path / "cyc" / "A.lean", "import B\n");
    putFile(tmp.path / "cyc" / "B.lean", "import A\n");
    Options oc = o;
    oc.root = (tmp.path / "cyc").u8string();
    bool threw = false;
    try {
        eng.build(oc);
    } catch (const std::runtime_error& e) {
        threw = true;
        check(std::string(e.what()).find("import cycle among: A, B") != std::string::npos,
              "cycle message");
    }
    check(threw, "build cycle throws");
    g_ran.clear();
    t.str("");
    rc = eng.verify(oc);
    check(rc == 0, "verify cycle ok");
    checkEq(joinNames(g_ran), "A,B", "verify cycle ran");
}

